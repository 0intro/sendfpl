import java.util.Base64
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    alias(libs.plugins.kotlin.multiplatform)
}

/**
 * The route files under src/commonTest/resources/routes as Kotlin, for tests on every platform:
 * only the JVM's tests have a class path to read a resource from. Base64 in chunks joined at run
 * time, since the JVM holds a string constant to 64 KiB.
 */
abstract class GenerateRouteFiles : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val routes: DirectoryProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val files = routes.get().asFile.listFiles().orEmpty().filter { it.isFile }.sortedBy { it.name }
        val out = StringBuilder()
        out.append("package app.sendfpl.route\n\n")
        out.append("/** The test route files, by name, in Base64. Generated by :cxp:generateRouteFiles. */\n")
        out.append("internal val ROUTE_FILES: Map<String, String> = mapOf(\n")
        for (f in files) {
            val chunks = Base64.getEncoder().encodeToString(f.readBytes()).chunked(30_000)
            out.append("    \"${f.name}\" to listOf(\n")
            for (c in chunks) out.append("        \"$c\",\n")
            out.append("    ).joinToString(\"\"),\n")
        }
        out.append(")\n")
        val dir = outputDir.get().asFile.resolve("app/sendfpl/route").apply { mkdirs() }
        dir.resolve("RouteFiles.kt").writeText(out.toString())
    }
}

val generateRouteFiles = tasks.register<GenerateRouteFiles>("generateRouteFiles") {
    routes.set(layout.projectDirectory.dir("src/commonTest/resources/routes"))
    outputDir.set(layout.buildDirectory.dir("generated/routeFiles"))
}

/*
 * The Connext protocol and the route model, which the apps and the trainer harness share. It
 * applies the Multiplatform plugin alone, so an Android import here fails to compile. The JVM
 * target is what the Android app consumes, and it has to be Java 17 bytecode, as the app is, or
 * AGP rejects it. linuxX64 runs the common tests natively on a Linux machine.
 */
kotlin {
    jvm {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }
    linuxX64()

    sourceSets {
        commonTest {
            kotlin.srcDir(generateRouteFiles)
            dependencies {
                implementation(libs.kotlin.test)
            }
        }
    }
}
